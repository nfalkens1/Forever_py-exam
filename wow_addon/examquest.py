#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
examquest.py  ·  the companion of the ExamQuest WoW addon

A WoW addon can't read files or run programs, so this side does the
work and talks to the game through the addon's own Lua files, which
/reload re-reads:

  install   copy the addon into <wow>/Interface/AddOns/ExamQuest and
            write Pool.lua (the Exam Rank 03 exercises, with subjects)
  watch     grade rendu/<exercise>.py whenever you save it; a pass bumps
            that exercise's counter in Results.lua and archives your file
  grade     grade one exercise once
  new       write rendu/<exercise>.py with just the signature

Uses this repo's grader (sandboxed subprocess) and banks unchanged.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import shutil
import sys
import time
from typing import Any, Dict, List, Optional

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, REPO)

from examshell import bank_common, grader, ranks, settings  # noqa: E402

ADDON_SRC = os.path.join(HERE, "ExamQuest")
CONFIG_PATH = os.path.join(settings.DATA_DIR, "examquest.json")
DEFAULT_RENDU = os.path.join(REPO, "rendu")
ARCHIVE = ".examquest_passed"

# WoW's fonts have no glyphs for these; the subjects use them.
ASCII = {
    "→": "->", "←": "<-", "—": "-", "–": "-", "…": "...", "’": "'",
    "‘": "'", "“": '"', "”": '"', "≤": "<=", "≥": ">=", "≠": "!=",
    "×": "x", "\t": "    ",
}


# ── config ─────────────────────────────────────────────────────────

def load_config() -> Dict[str, Any]:
    try:
        with open(CONFIG_PATH, encoding="utf-8") as fh:
            data: Dict[str, Any] = json.load(fh)
            return data
    except (OSError, ValueError):
        return {}


def save_config(cfg: Dict[str, Any]) -> None:
    os.makedirs(settings.DATA_DIR, exist_ok=True)
    with open(CONFIG_PATH, "w", encoding="utf-8") as fh:
        json.dump(cfg, fh, indent=2)


def addon_dir(cfg: Dict[str, Any]) -> str:
    wow = cfg.get("wow")
    if not wow:
        sys.exit("No WoW folder configured - run `examquest.py install "
                 "--wow <World of Warcraft/_forever_>` first.")
    return os.path.join(wow, "Interface", "AddOns", "ExamQuest")


# ── Lua output ─────────────────────────────────────────────────────

def lua_long_string(text: str) -> str:
    """text as a Lua long bracket string that can't be cut short."""
    level = 0
    while "]%s]" % ("=" * level) in text:
        level += 1
    eq = "=" * level
    # A newline right after the opening bracket is dropped by Lua.
    return "[%s[\n%s]%s]" % (eq, text, eq)


def wow_text(text: str) -> str:
    for src, dst in ASCII.items():
        text = text.replace(src, dst)
    return text


def write_atomic(path: str, text: str) -> None:
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.replace(tmp, path)


def pool_lua(rank: ranks.Rank) -> str:
    lines = [
        "-- Generated by examquest.py install. Do not edit.",
        "ExamQuest_Pool = {",
        "  rank = %s," % json.dumps(rank.id),
        "  label = %s," % json.dumps(rank.label),
        "  levels = %d," % rank.n_levels,
        "  exercises = {",
    ]
    for level in sorted(rank.levels):
        for name in rank.levels[level]:
            ex = rank.exercises[name]
            lines.append(
                "    { name = %s, level = %d, subject = %s },"
                % (json.dumps(name), level,
                   lua_long_string(wow_text(ex["subject"])))
            )
    lines += ["  },", "}", ""]
    return "\n".join(lines)


def results_lua(results: Dict[str, Dict[str, Any]]) -> str:
    lines = [
        "-- Written by examquest.py. Do not edit; "
        "it is overwritten on every pass.",
        "ExamQuest_Results = { exercises = {",
    ]
    for name in sorted(results):
        row = results[name]
        lines.append(
            "  [%s] = { passes = %d, last = %d },"
            % (json.dumps(name), row["passes"], row["last"])
        )
    lines += ["} }", ""]
    return "\n".join(lines)


# ── results (the companion's copy is the source of truth) ─────────

def results_path() -> str:
    return os.path.join(settings.DATA_DIR, "examquest_results.json")


def load_results() -> Dict[str, Dict[str, Any]]:
    try:
        with open(results_path(), encoding="utf-8") as fh:
            data: Dict[str, Dict[str, Any]] = json.load(fh)
            return data
    except (OSError, ValueError):
        return {}


def publish(cfg: Dict[str, Any], results: Dict[str, Dict[str, Any]]) -> None:
    os.makedirs(settings.DATA_DIR, exist_ok=True)
    write_atomic(results_path(), json.dumps(results, indent=2))
    write_atomic(os.path.join(addon_dir(cfg), "Results.lua"),
                 results_lua(results))


# ── grading ────────────────────────────────────────────────────────

# Only the Python Exam Rank 03 pool, on purpose.
RANK = "03"


def rank_of(cfg: Dict[str, Any]) -> ranks.Rank:
    return ranks.get(RANK)


def grade_one(name: str, rank: ranks.Rank, rendu: str) -> grader.Report:
    ex = rank.exercises[name]
    report = grader.grade(name, ex, rendu, rng=random.Random())
    if report.ok:
        print("  SUCCESS  %s  (%d/%d tests)"
              % (name, report.passed, report.total))
    elif report.fatal:
        print("  FAILURE  %s  %s" % (name, report.fatal_title))
        if report.detail:
            print("           %s" % report.detail)
    else:
        print("  FAILURE  %s  (%d/%d tests)"
              % (name, report.passed, report.total))
        for fail in report.failures[:3]:
            print("    %s" % fail.call(report.function))
            print("      expected %s" % grader.short_repr(fail.expected))
            # got is already a repr made inside the sandbox.
            print("      got      %s" % fail.got)
        more = len(report.failures) - 3
        if more > 0:
            print("    … and %d more" % more)
    for warning in report.warnings:
        print("  warning: %s" % warning)
    return report


def record_pass(cfg: Dict[str, Any], name: str) -> int:
    results = load_results()
    row = results.setdefault(name, {"passes": 0, "last": 0})
    row["passes"] += 1
    row["last"] = int(time.time())
    publish(cfg, results)
    passes: int = row["passes"]
    return passes


def archive(rendu: str, name: str) -> str:
    folder = os.path.join(rendu, ARCHIVE)
    os.makedirs(folder, exist_ok=True)
    dst = os.path.join(folder, "%s.%s.py"
                       % (name, time.strftime("%Y%m%d-%H%M%S")))
    shutil.move(os.path.join(rendu, name + ".py"), dst)
    return dst


def handle(cfg: Dict[str, Any], name: str, rendu: str, keep: bool) -> None:
    print(time.strftime("[%H:%M:%S]"), "grading", name)
    report = grade_one(name, rank_of(cfg), rendu)
    if not report.ok:
        return
    passes = record_pass(cfg, name)
    print("  -> pass #%d recorded. /reload in WoW to update the quest."
          % passes)
    if not keep:
        moved = os.path.basename(archive(rendu, name))
        print("  -> moved to rendu/%s/%s (next time: from scratch)"
              % (ARCHIVE, moved))


# ── commands ───────────────────────────────────────────────────────

def cmd_install(args: argparse.Namespace) -> None:
    cfg = load_config()
    if args.wow:
        cfg["wow"] = os.path.abspath(args.wow)
    dst = addon_dir(cfg)
    if not os.path.isdir(os.path.join(cfg["wow"], "Interface")) \
            and not args.force:
        sys.exit("%s has no Interface folder - is it really the Forever "
                 "client folder (…/World of Warcraft/_forever_)? "
                 "--force to install anyway." % cfg["wow"])
    os.makedirs(dst, exist_ok=True)
    for fname in ("ExamQuest.toc", "Core.lua", "UI.lua"):
        shutil.copyfile(os.path.join(ADDON_SRC, fname),
                        os.path.join(dst, fname))
    rank = rank_of(cfg)
    write_atomic(os.path.join(dst, "Pool.lua"), pool_lua(rank))
    save_config(cfg)
    publish(cfg, load_results())
    print("Installed ExamQuest into %s" % dst)
    print("Pool: %s, %d exercises in %d levels."
          % (rank.label, len(rank.exercises), rank.n_levels))
    print("Restart WoW once (new addon); after that /reload is enough.")


def changed_files(rendu: str, names: List[str],
                  seen: Dict[str, str]) -> List[str]:
    out = []
    for name in names:
        path = os.path.join(rendu, name + ".py")
        try:
            with open(path, "rb") as fh:
                digest = hashlib.sha1(fh.read()).hexdigest()
        except OSError:
            seen.pop(name, None)
            continue
        if seen.get(name) != digest:
            seen[name] = digest
            out.append(name)
    return out


def cmd_watch(args: argparse.Namespace) -> None:
    cfg = load_config()
    addon_dir(cfg)  # fail early when not installed
    rank = rank_of(cfg)
    rendu = os.path.abspath(args.rendu)
    os.makedirs(rendu, exist_ok=True)
    names = sorted(rank.exercises)
    seen: Dict[str, str] = {}
    # Files that already exist are not graded on start, only on change.
    changed_files(rendu, names, seen)
    print("Watching %s for %s exercises. Ctrl-C to stop."
          % (rendu, rank.label))
    try:
        while True:
            time.sleep(args.interval)
            for name in changed_files(rendu, names, seen):
                # Let the editor finish writing.
                time.sleep(0.3)
                handle(cfg, name, rendu, args.keep)
                changed_files(rendu, [name], seen)
    except KeyboardInterrupt:
        print()


def cmd_grade(args: argparse.Namespace) -> None:
    cfg = load_config()
    if args.exercise not in rank_of(cfg).exercises:
        sys.exit("%s is not in the %s pool" % (args.exercise,
                                               rank_of(cfg).label))
    handle(cfg, args.exercise, os.path.abspath(args.rendu), args.keep)


def cmd_new(args: argparse.Namespace) -> None:
    rank = rank_of(load_config())
    ex = rank.exercises.get(args.exercise)
    if ex is None:
        sys.exit("%s is not in the %s pool" % (args.exercise, rank.label))
    rendu = os.path.abspath(args.rendu)
    path = os.path.join(rendu, args.exercise + ".py")
    if os.path.exists(path):
        sys.exit("%s already exists" % path)
    defs = []
    for part in grader.parts_of(ex):
        sig = (bank_common.signature_for(ex["subject"], part["function"])
               or "def %s():" % part["function"])
        defs.append("%s\n    pass\n" % sig)
    os.makedirs(rendu, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n\n".join(defs))
    print("wrote %s" % path)


def main(argv: Optional[List[str]] = None) -> None:
    ap = argparse.ArgumentParser(prog="examquest.py", description=__doc__,
                                 formatter_class=argparse.RawTextHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("install", help="install the addon + pool")
    p.add_argument("--wow", help="the WoW Forever folder "
                   "(…/World of Warcraft/_forever_)")
    p.add_argument("--force", action="store_true")
    p.set_defaults(func=cmd_install)

    for name, func, hlp in (
        ("watch", cmd_watch, "grade rendu/ files on save"),
        ("grade", cmd_grade, "grade one exercise now"),
        ("new", cmd_new, "write a signature-only stub"),
    ):
        p = sub.add_parser(name, help=hlp)
        if name != "watch":
            p.add_argument("exercise")
        p.add_argument("--rendu", default=DEFAULT_RENDU)
        if name != "new":
            p.add_argument("--keep", action="store_true",
                           help="don't archive a passing file")
        if name == "watch":
            p.add_argument("--interval", type=float, default=1.0)
        p.set_defaults(func=func)

    args = ap.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
